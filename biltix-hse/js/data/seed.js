export const ANCHOR_DATE = '2026-11-09';
export const TIMEZONE_OFFSET = '+03:00';

const ANCHOR_UTC = Date.UTC(2026, 10, 9);
const DAY_MS = 86_400_000;
const pad2 = (n) => String(n).padStart(2, '0');

/** تاريخ ISO (YYYY-MM-DD) بإزاحة أيام عن المرجع. */
function d(offsetDays = 0) {
  const x = new Date(ANCHOR_UTC + offsetDays * DAY_MS);
  return `${x.getUTCFullYear()}-${pad2(x.getUTCMonth() + 1)}-${pad2(x.getUTCDate())}`;
}

/** طابع زمني ISO كامل بتوقيت الرياض بإزاحة أيام ووقت محلي HH:MM. */
function t(offsetDays, hhmm) {
  return `${d(offsetDays)}T${hhmm}:00${TIMEZONE_OFFSET}`;
}

/** "الآن" المرجعي للبيانات اللحظية (آخر مزامنة، قراءات الحساسات). */
export const ANCHOR_NOW = t(0, '12:40');

/** مولّد أرقام عشوائية حتمي — mulberry32. */
function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6D2B79F5) >>> 0;
    let x = a;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

