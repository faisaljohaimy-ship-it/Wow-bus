// 2. المشاريع — مؤشرات القيمة المكتسبة (EVM)
//    BAC = الميزانية؛ PV = BAC × النسبة المخططة؛ EV = BAC × النسبة المنجزة؛
//    AC = EV / CPI؛ EAC = BAC / CPI؛ ETC = EAC − AC؛ VAC = BAC − EAC.
// ------------------------------------------------------------------

function evmFor(BAC, plannedPct, donePct, CPI) {
  const PV = r0(BAC * plannedPct / 100);
  const EV = r0(BAC * donePct / 100);
  const AC = r0(EV / CPI);
  const SPI = PV > 0 ? r2(EV / PV) : 1;
  const EAC = r0(BAC / CPI);
  return { BAC, PV, EV, AC, CPI: r2(CPI), SPI, EAC, ETC: EAC - AC, VAC: BAC - EAC };
}

function project(p) {
  return {
    ...p,
    evm: evmFor(p.budgetSAR, p.plannedPercent, p.percentComplete, p.cpi),
    weights: null,
  };
}

