export const PLATFORM_ANCHOR_DATE = '2026-11-09';
const TZ = '+03:00';
const ANCHOR_UTC = Date.UTC(2026, 10, 9);
const DAY_MS = 86_400_000;
const pad2 = (n) => String(n).padStart(2, '0');

/** تاريخ ISO (YYYY-MM-DD) بإزاحة أيام عن المرجع. */
function d(offsetDays = 0) {
  const x = new Date(ANCHOR_UTC + offsetDays * DAY_MS);
  return `${x.getUTCFullYear()}-${pad2(x.getUTCMonth() + 1)}-${pad2(x.getUTCDate())}`;
}

/** طابع زمني ISO كامل بتوقيت الرياض بإزاحة أيام ووقت محلي HH:MM. */
function t(offsetDays, hhmm) {
  return `${d(offsetDays)}T${hhmm}:00${TZ}`;
}

/** تسميات شهرية YYYY-MM لعدد `count` شهراً تنتهي بالشهر الذي يبعد `endOffset` عن شهر المرجع. */
function months(count, endOffset = 0) {
  const out = [];
  for (let i = count - 1; i >= 0; i -= 1) {
    const x = new Date(Date.UTC(2026, 10 + endOffset - i, 1));
    out.push(`${x.getUTCFullYear()}-${pad2(x.getUTCMonth() + 1)}`);
  }
  return out;
}

const r0 = (n) => Math.round(n);
const r1 = (n) => Math.round(n * 10) / 10;
const r2 = (n) => Math.round(n * 100) / 100;

