const PRECACHE_SET = new Set(PRECACHE.map((p) => new URL(p, self.registration.scope).href));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL);
    // One file at a time in small batches; a missing file never aborts the install (addAll would).
    const queue = PRECACHE.slice();
    const worker = async () => {
      while (queue.length) {
        const path = queue.shift();
        try {
          const res = await fetch(new Request(path, { cache: 'no-cache', credentials: 'same-origin' }));
          if (res.ok && !res.redirected) await cache.put(path, res);
        } catch { /* offline during install: the runtime cache fills in later */ }
      }
    };
    await Promise.all([worker(), worker(), worker(), worker()]);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keep = new Set([SHELL, RUNTIME]);
    for (const name of await caches.keys()) if (name.startsWith('biltix-') && !keep.has(name)) await caches.delete(name);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'version' && event.ports && event.ports[0]) event.ports[0].postMessage({ version: VERSION, newerBuildSeen });
});

function shellKey(url) {
  const u = new URL(url);
  return new URL('./', self.registration.scope).href === u.origin + u.pathname || u.pathname.endsWith('/index.html') ? './' : null;
}

async function fromCaches(request) {
  const shell = await caches.open(SHELL);
  const hit = await shell.match(request);
  if (hit) return hit;
  const rt = await caches.open(RUNTIME);
  return rt.match(request);
}

async function navigate(request) {
  const shell = await caches.open(SHELL);
  const cached = await shell.match('./');
  const network = (async () => {
    const res = await fetch(request);
    if (res.ok && res.type === 'basic') {
      const html = await res.clone().text();
      const m = html.match(BUILD_RE);
      if (m && m[1] !== VERSION) newerBuildSeen = true;
      // Only this build's own shell is stored. A 200 page without the stamp (a captive-portal sign-in page, a host
      // error page) never replaces the cached app.
      else if (m && !res.redirected) await shell.put('./', new Response(html, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } }));
    }
    return res;
  })();
  if (!cached) return network.catch(() => offlinePage());
  const timeout = new Promise((resolve) => setTimeout(() => resolve(null), NAV_TIMEOUT_MS));
  try {
    const res = await Promise.race([network, timeout]);
    return res || cached;
  } catch { return cached; }
}

/**
 * A document in this scope that is not the app shell (the Markdown plan linked from #/golive, a file opened in its
 * own tab): network first, the runtime cache as the offline fallback. Never stored as the shell.
 */
async function otherDocument(request) {
  try {
    const res = await fetch(request);
    if (res.ok && res.type === 'basic' && !res.redirected) {
      const rt = await caches.open(RUNTIME);
      await rt.put(request, res.clone());
    }
    return res;
  } catch {
    return (await fromCaches(request)) || offlinePage();
  }
}

async function staleWhileRevalidate(event, request) {
  const rt = await caches.open(RUNTIME);
  const cached = await rt.match(request);
  const update = fetch(request).then(async (res) => {
    if (res.ok && res.type === 'basic' && !res.redirected) await rt.put(request, res.clone());
    return res;
  });
  if (cached) { event.waitUntil(update.catch(() => null)); return cached; }
  return update;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.searchParams.has('build-check') || url.pathname.endsWith('/sw.js')) return;
  if (request.headers.has('range') || request.destination === 'video' || request.destination === 'audio' || /\.(mp4|webm|mov)$/i.test(url.pathname)) return;

  // The app shell (the scope root or …/index.html), however it is requested.
  if (shellKey(request.url)) {
    event.respondWith(navigate(request));
    return;
  }
  // Any other navigation in scope is its own document, not the app: it must not be answered with, or saved as, the shell.
  if (request.mode === 'navigate') {
    event.respondWith(otherDocument(request));
    return;
  }
  // A newer build is published: forward to the network (cache only as an offline fallback) until it takes over.
  if (newerBuildSeen) {
    event.respondWith(fetch(request).catch(() => fromCaches(request).then((r) => r || Response.error())));
    return;
  }
  if (PRECACHE_SET.has(url.origin + url.pathname) && !url.search) {
    event.respondWith(caches.open(SHELL).then((c) => c.match(request)).then((hit) => hit || staleWhileRevalidate(event, request)));
    return;
  }
  event.respondWith(staleWhileRevalidate(event, request).catch(() => fromCaches(request).then((r) => r || Response.error())));
});

function offlinePage() {
  const body = '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BILTIX Risk AI</title>'
    + '<body style="font-family:system-ui,sans-serif;margin:2rem;line-height:1.6;color:#0b1b2b;background:#f4f7fb">'
    + '<h1 style="font-size:1.25rem">BILTIX Risk AI</h1>'
    + '<p lang="ar" dir="rtl">دون اتصال — لم تُحفظ نسخة من التطبيق على هذا الجهاز بعد. افتح الصفحة مرة واحدة مع اتصال بالإنترنت.</p>'
    + '<p lang="en" dir="ltr">Offline — this device has no saved copy of the app yet. Open the page once while online.</p></body>';
  return new Response(body, { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
}
