/*
 * BILTIX Risk AI — service worker (root scope). Registered by js/core/offline.js as sw.js?v=<build stamp>
 * (<meta name="biltix-build">, tools/stamp-build.mjs). Guide: docs/offline.md.
 *
 *   Precache   the app shell, every view module, i18n, CSS, fonts, the explainer posters and the previews of the
 *              simulated 360° captures (list below, kept in sync by `node tools/sw-precache.mjs`;
 *              tests/field.test.mjs fails when it drifts). The big MP4s are never cached (Range requests pass
 *              straight to the network); a full panorama is cached at runtime the first time it is opened.
 *   Versioned  caches are named per build: biltix-shell-<v> (precache, served cache-first, never revalidated
 *              piecemeal so one build never mixes with another) and biltix-rt-<v> (stale-while-revalidate for
 *              any other same-origin GET). A new stamp → a new worker → precache → skipWaiting → old caches
 *              deleted on activate.
 *   index.html network-first (5 s timeout when a cached copy exists), cached copy offline. When the network
 *              HTML carries a different build stamp than this worker (a publish happened), this worker stops
 *              answering from its cache and forwards to the network until the new worker takes over — so the
 *              reload offered by app.js watchForNewBuild() never runs old modules under a new page. Only HTML
 *              that carries this worker's stamp is saved as the shell.
 *   Other      documents in scope (docs/golive/plan.md opened from #/golive, a file opened in a tab) are
 *   documents  network-first with the runtime cache as fallback; they are never treated as the shell.
 *   Bypassed   non-GET, other origins, ?build-check= (app.js new-version check), Range / media requests.
 */
