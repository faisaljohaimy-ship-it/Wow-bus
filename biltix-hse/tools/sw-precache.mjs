// Rewrites the PRECACHE list in sw.js from the files on disk (no build step: run it after adding or removing a
// module, stylesheet, font or poster). `node tools/sw-precache.mjs --check` exits 1 when sw.js is out of date.
// Included: ./ (index.html), js/**/*.js, css/*.css, assets/fonts/*.woff2, assets/video/*.webp + *.vtt,
// assets/favicon.svg, assets/manifest.webmanifest. Never the MP4s (large; streamed with Range requests).
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else out.push(relative(root, p).split(sep).join('/'));
  }
  return out;
}

export function precacheList() {
  const files = [
    ...walk(join(root, 'js')).filter((f) => f.endsWith('.js')),
    ...walk(join(root, 'css')).filter((f) => f.endsWith('.css')),
    ...walk(join(root, 'assets/fonts')).filter((f) => f.endsWith('.woff2')),
    ...walk(join(root, 'assets/video')).filter((f) => /\.(webp|vtt)$/.test(f)),
    'assets/favicon.svg',
    'assets/manifest.webmanifest',
  ].sort();
  return ['./', ...files];
}

export function renderBlock(list = precacheList()) {
  return `/* BEGIN PRECACHE (generated by tools/sw-precache.mjs — do not edit by hand) */\nconst PRECACHE = [\n${list.map((f) => `  '${f}',`).join('\n')}\n];\n/* END PRECACHE */`;
}

const BLOCK_RE = /\/\* BEGIN PRECACHE[\s\S]*?\/\* END PRECACHE \*\//;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const swPath = join(root, 'sw.js');
  const src = readFileSync(swPath, 'utf8');
  const next = src.replace(BLOCK_RE, renderBlock());
  if (process.argv.includes('--check')) {
    if (next !== src) { console.error('sw.js PRECACHE is out of date: run node tools/sw-precache.mjs'); process.exit(1); }
    console.log('sw.js PRECACHE is up to date');
  } else {
    writeFileSync(swPath, next);
    console.log(`sw.js PRECACHE: ${precacheList().length} entries`);
  }
}
