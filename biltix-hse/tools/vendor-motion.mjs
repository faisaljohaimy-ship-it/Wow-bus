#!/usr/bin/env node
/**
 * BILTIX Risk AI — vendor the Motion animation library (motion.dev, MIT) as ONE browser ES module.
 *
 *   node biltix-hse/tools/vendor-motion.mjs [--work <scratch dir>] [--keep]
 *
 * What it does
 *   1. Creates a throw-away npm project OUTSIDE the repository (default: <os tmpdir>/biltix-vendor-motion-<pid>,
 *      or --work <dir>) and installs the pinned versions below into it. Nothing is added to the repo's
 *      package.json; the static site keeps zero runtime npm dependencies.
 *   2. Bundles `animate` from `motion/mini` (Motion's vanilla Web Animations API build of animate()) and
 *      `stagger` from `motion` with esbuild into a single minified ESM file:
 *        biltix-hse/js/vendor/motion.js
 *      with a header naming the source package, version, licence and this rebuild command.
 *   3. Copies the package licence to biltix-hse/js/vendor/MOTION-LICENSE.txt.
 *   4. Smoke-checks the output (exports `animate` and `stagger`, no bare imports, no `process`).
 *
 * Why the mini build: the hybrid `animate` from `motion` (springs, independent transforms, JS values,
 * sequences) bundles to ~73 KB minified; the WAAPI-backed mini `animate` + `stagger` is ~10 KB and covers
 * everything js/ui/motion.js needs (opacity/transform keyframes, cubic-bezier easing, delays, stagger,
 * `.finished` promises, interruption). Numeric count-ups are done in js/ui/motion.js with rAF.
 *
 * Requires Node ≥ 18 and network access to the npm registry. Re-run after bumping MOTION_VERSION.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync, existsSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MOTION_VERSION = '14.11.1';
const ESBUILD_VERSION = '0.28.2';

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, '..');                       // biltix-hse/
const vendorDir = join(siteRoot, 'js', 'vendor');
const outFile = join(vendorDir, 'motion.js');
const licenseOut = join(vendorDir, 'MOTION-LICENSE.txt');

const args = process.argv.slice(2);
const argValue = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
const keep = args.includes('--keep');
const workArg = argValue('--work');
const work = workArg ? resolve(workArg) : mkdtempSync(join(tmpdir(), 'biltix-vendor-motion-'));
if (work.startsWith(siteRoot)) {
  console.error(`[vendor-motion] refusing to install inside the site (${work}); pass --work outside biltix-hse/`);
  process.exit(2);
}
mkdirSync(work, { recursive: true });

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const run = (cmd, argv) => execFileSync(cmd, argv, { cwd: work, stdio: ['ignore', 'pipe', 'inherit'] }).toString();

console.log(`[vendor-motion] work dir: ${work}`);
writeFileSync(join(work, 'package.json'), JSON.stringify({ name: 'biltix-vendor-motion', private: true, type: 'module' }, null, 2));
run(npm, ['install', '--no-audit', '--no-fund', '--save-exact', `motion@${MOTION_VERSION}`, `esbuild@${ESBUILD_VERSION}`]);

const installed = JSON.parse(readFileSync(join(work, 'node_modules', 'motion', 'package.json'), 'utf8'));
if (installed.version !== MOTION_VERSION) throw new Error(`expected motion@${MOTION_VERSION}, got ${installed.version}`);
if (installed.license !== 'MIT') throw new Error(`unexpected licence for motion: ${installed.license}`);

const entry = join(work, 'entry.mjs');
writeFileSync(entry, [
  "export { animate } from 'motion/mini';",
  "export { stagger } from 'motion';",
  '',
].join('\n'));

const header = [
  '/*!',
  ` * Motion ${MOTION_VERSION} (https://motion.dev) — vendored for BILTIX Risk AI.`,
  ` * Source: npm package "motion@${MOTION_VERSION}" — exports \`animate\` (from "motion/mini", the vanilla`,
  ' *   Web Animations API build) and `stagger` (from "motion"), bundled and minified with esbuild',
  ` *   ${ESBUILD_VERSION} as one browser ES module. No other code is added or changed.`,
  ' * Licence: MIT, Copyright (c) 2024 Motion B.V. — full text in js/vendor/MOTION-LICENSE.txt.',
  ' * Rebuild: node biltix-hse/tools/vendor-motion.mjs   (do not edit this file by hand)',
  ' */',
].join('\n');

const esbuild = await import(pathToFileURL(join(work, 'node_modules', 'esbuild', 'lib', 'main.js')).href);
const result = await esbuild.build({
  entryPoints: [entry],
  absWorkingDir: work,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020', 'chrome90', 'safari15', 'firefox90'],
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: header },
  write: false,
  logLevel: 'warning',
});
const code = result.outputFiles[0].text;

/* smoke checks (on the bundle body, not the header comment) */
const body = code.replace(header, '');
if (/\bimport\s*["'(]|from\s*["'][^./]/.test(body)) throw new Error('bundle still contains bare imports');
// `typeof process<"u"` guards may survive minification (harmless in browsers); member access must not.
if (/\bprocess\s*\./.test(body)) throw new Error('bundle still reads `process.*`');
if (!/export\s*\{[^}]*\banimate\b[^}]*\}/.test(body) || !/\bstagger\b/.test(body)) throw new Error('bundle does not export animate/stagger');

mkdirSync(vendorDir, { recursive: true });
writeFileSync(outFile, code.endsWith('\n') ? code : `${code}\n`);
const licenseSrc = ['LICENSE.md', 'LICENSE', 'license'].map((f) => join(work, 'node_modules', 'motion', f)).find((p) => existsSync(p));
if (!licenseSrc) throw new Error('motion licence file not found');
copyFileSync(licenseSrc, licenseOut);

const size = statSync(outFile).size;
console.log(`[vendor-motion] wrote ${outFile} (${size} bytes) and ${licenseOut}`);
if (!keep && !workArg) rmSync(work, { recursive: true, force: true });
